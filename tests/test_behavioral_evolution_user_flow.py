def test_evolution_varies_across_different_patterns():
    """Ensures that distinct incident inputs yield distinct behavioral evolution trajectories."""
    property_incident = {
        "scenario_title": "Commercial Petty Theft",
        "incident_date": "2024-04-10",
        "incident_time": "14:10",
        "crime_category": "theft",
        "location_type": "commercial",
        "is_weekend": False,
        "has_property": True,
        "property_value": 300.0,
        "has_weapon": False,
        "has_injury": False
    }

    violent_incident = {
        "scenario_title": "Armed Night Street Robbery",
        "incident_date": "2024-08-22",
        "incident_time": "01:45",
        "crime_category": "robbery",
        "location_type": "street_outdoor",
        "is_weekend": True,
        "has_property": True,
        "property_value": 850.0,
        "has_weapon": True,
        "weapon_count": 1,
        "has_injury": True
    }

    res_prop = analysis_engine.analyze(property_incident)
    res_viol = analysis_engine.analyze(violent_incident)

    evo_prop = res_prop["behavioral_evolution"]
    evo_viol = res_viol["behavioral_evolution"]

    # Patterns should differ
    assert evo_prop["pattern_identifier"] != evo_viol["pattern_identifier"]
    assert evo_prop["pattern_name"] != evo_viol["pattern_name"]

    # Formulas across stages should reflect distinct behavioral profiles
    assert evo_prop["timeline_stages"][0]["behavioral_formula"] != evo_viol["timeline_stages"][0]["behavioral_formula"]
    assert evo_viol["timeline_stages"][0]["metrics"]["weapon_presence_pct"] > evo_prop["timeline_stages"][0]["metrics"]["weapon_presence_pct"]


def test_api_analyze_input_returns_evolution_timeline(client: TestClient):
    """Validates that POST /api/analyze/input serves behavioral_evolution schema over HTTP."""
    payload = {
        "scenario_title": "Convenience Store Holdup",
        "incident_date": "2024-11-05",
        "incident_time": "21:15",
        "crime_category": "robbery",
        "location_type": "commercial",
        "is_weekend": False,
        "has_property": True,
        "property_value": 1200.0,
        "has_weapon": True,
        "weapon_count": 1,
        "has_injury": False
    }

    response = client.post("/api/analyze/input", json=payload)
    assert response.status_code == 200

    data = response.json()
    assert "behavioral_evolution" in data
    evo = data["behavioral_evolution"]

    assert evo["pattern_identifier"].startswith("CCP_")
    assert evo["evolution_interpretation"] == "Behavioral characteristics changed over the observed historical period."
    assert len(evo["timeline_stages"]) == 3

    assert evo["timeline_stages"][0]["period_label"] == "EARLY PERIOD"
    assert evo["timeline_stages"][1]["period_label"] == "MIDDLE PERIOD"
    assert evo["timeline_stages"][2]["period_label"] == "LATER PERIOD"

    for stage in evo["timeline_stages"]:
        assert "behavioral_formula" in stage
        assert "behavioral_characteristics" in stage
        assert "metrics" in stage
        assert stage["metrics"]["incident_volume"] > 0

    assert "ethical_advisory" in evo
    assert "not indicate sequential actions by an individual offender" in evo["ethical_advisory"]
