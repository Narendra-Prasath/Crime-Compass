def test_evolution_service_standalone_timeline():
    """Validates the structure and metrics of the timeline generated by evolution_service."""
    test_incident = {
        "scenario_title": "Late Night Residential Burglary",
        "incident_date": "2024-03-20",
        "incident_time": "02:15",
        "crime_category": "burglary",
        "location_type": "residential",
        "is_weekend": True,
        "has_property": True,
        "property_value": 3200.0,
        "has_weapon": False,
        "has_injury": False
    }

    timeline = evolution_service.build_evolution_timeline(
        input_data=test_incident,
        cl_id=3,
        cl_name="Residential Property Infiltration",
        state=state
    )

    # 1. Structural assertions
    assert timeline["pattern_identifier"] == "CCP_03"
    assert "Burglary" in timeline["pattern_name"]
    assert "12-Month Historical Observation Period" in timeline["dataset_time_span"]

    # 2. Strict interpretation requirement
    expected_interpretation = "Behavioral characteristics changed over the observed historical period."
    assert timeline["evolution_interpretation"] == expected_interpretation

    # 3. Three-stage timeline
    stages = timeline["timeline_stages"]
    assert len(stages) == 3
    assert [s["stage_id"] for s in stages] == ["early", "middle", "later"]

    # Verify Early stage
    early = stages[0]
    assert early["period_label"] == "EARLY PERIOD"
    assert "January – April" in early["time_range"]
    assert " + " in early["behavioral_formula"]
    assert len(early["behavioral_characteristics"]) >= 3
    assert early["metrics"]["incident_volume"] > 0
    assert 0.0 <= early["metrics"]["nighttime_pct"] <= 100.0
    assert 0.0 <= early["metrics"]["weapon_presence_pct"] <= 100.0

    # Verify Middle stage
    middle = stages[1]
    assert middle["period_label"] == "MIDDLE PERIOD"
    assert "May – August" in middle["time_range"]
    assert " + " in middle["behavioral_formula"]
    assert len(middle["behavioral_characteristics"]) >= 3
    assert middle["metrics"]["incident_volume"] > 0

    # Verify Later stage
    later = stages[2]
    assert later["period_label"] == "LATER PERIOD"
    assert "September – December" in later["time_range"]
    assert " + " in later["behavioral_formula"]
    assert len(later["behavioral_characteristics"]) >= 3
    assert later["metrics"]["incident_volume"] > 0

    # Total volume across 3 periods should equal cluster volume
    total_cluster_vol = sum(s["metrics"]["incident_volume"] for s in stages)
    assert total_cluster_vol == 33335  # Exact Cluster 3 empirical count

    # 4. Ethical non-offender advisory
    assert "not indicate sequential actions by an individual offender" in timeline["ethical_advisory"]


